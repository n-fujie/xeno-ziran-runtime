import collections
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
P = ROOT / "docs/ecosystem/perf_stage5/paired"
F = ROOT / "docs/ecosystem/stage5_fragments"
F.mkdir(parents=True, exist_ok=True)
A, X1, POOL = (json.loads((P / n).read_text()) for n in ("analysis.json", "analysis_excluding_1.json", "analysis_pooled_stage4_acceptance.json"))


def tbl(head, rows):
    return "\n".join(["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|", *("| " + " | ".join(str(c) for c in r) + " |" for r in rows)]) + "\n"


def pair_rows(d, pair, measures=None):
    a, b = pair.split("/")[1], pair.split("/")[0]
    rows = d["pairs"][pair]
    return [[r["camera"], r["mode"], r["measure"], r[f"{a}_median"], r[f"{b}_median"], r["paired_ratio_median"], f"[{r['ci95'][0]}, {r['ci95'][1]}]", r["verdict"]] for r in rows if measures is None or r["measure"] in measures], a, b


def counts(d, pair):
    c = collections.Counter(r["verdict"] for r in d["pairs"][pair])
    return ", ".join(f"{c.get(k, 0)} {k}" for k in ("regression", "no meaningful regression", "inconclusive"))


full = []
for d, name in ((A, "all 6 repetitions (primary)"), (X1, "repetition 1 excluded (sensitivity)")):
    for pair in d["pairs"]:
        rows, a, b = pair_rows(d, pair)
        full.append(f"## {pair}, {name}\n\n" + tbl(["camera", "mode", "measure", f"{a} (ms)", f"{b} (ms)", "paired ratio", "95 % CI", "verdict"], rows))
(P / "analysis_tables.md").write_text("# Paired comparison tables (generated by frontend/scripts/perf_fragments.py from analysis*.json)\n\n" + "\n".join(full))

loads = sorted(A["load"].items())
hi = [k for k, v in loads if float(v.split()[2]) > 10]
lo = [float(v.split()[2]) for k, v in loads if k not in hi]
head5, a5, b5 = pair_rows(A, "stage5/stage4")
key = [r for r in head5 if r[2] in ("median", "p95")]
s3 = [r for r in pair_rows(A, "stage5/stage3", ("median", "p95"))[0]]
ctr = A["counters"]
cnt_rows = []
for cam in ("habitat", "overview", "body", "habitat+research", "habitat+technical"):
    for b in ("stage3", "stage4", "stage5"):
        c = ctr[b].get(cam)
        if not c:
            continue
        s = c["orbit_series"]
        cnt_rows.append([cam, b, c["draw_calls_static"], int(c["triangles_static"]), s["geometry_uploads"] if s else "n/a", s["programs_built"] if s else "n/a", s["lod_switches"] if s else "n/a", s["visibility_flips"] if s else "n/a"])
absolute = []
import statistics  # noqa: E402

for pair in ("stage4/stage3", "stage5/stage4"):
    pass
