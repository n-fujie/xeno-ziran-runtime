import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { Mirror } from '../lod/mirror';
import { decodeFrame, dequantize } from './decode';

const dir = join(dirname(fileURLToPath(import.meta.url)), '__fixtures__');
const buf = (name: string) => {
  const b = readFileSync(join(dir, name));
  return b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength) as ArrayBuffer;
};
const expected = JSON.parse(readFileSync(join(dir, 'expected.json'), 'utf8'));

describe('binary protocol (fixtures generated by the backend encoder)', () => {
  it('decodes delta frames section by section', () => {
    const f = decodeFrame(buf('frame.bin'));
    if (f.type !== 'deltas') throw new Error('wrong frame type');
    expect(f.steps.length).toBe(expected.steps.length);
    f.steps.forEach((d, i) => {
      const e = expected.steps[i];
      expect(d.t).toBe(e.t);
      expect(Array.from(d.diffIdx ?? [])).toEqual(e.diffIdx);
      expect(Array.from(d.diffQ ?? [])).toEqual(e.diffQ);
      expect(d.diffDense ? Array.from(d.diffDense) : null).toEqual(e.diffDense);
      expect(Array.from(d.ignitions ?? [])).toEqual(e.ignitions);
      expect(Array.from(d.penetrations?.edge ?? [])).toEqual(e.penetrationEdges);
      expect(Array.from(d.cuts ?? [])).toEqual(e.cuts);
      expect(Array.from(d.newConnections?.edge ?? [])).toEqual(e.newEdges);
      expect(Array.from(d.gateEdge ?? [])).toEqual(e.gateEdge);
      expect(Array.from(d.returns ?? [])).toEqual(e.returns);
      expect(Array.from(d.reconfigurations?.edge ?? [])).toEqual(e.reconfEdges);
    });
  });

  it('decodes snapshots and aggregates', () => {
    const s = decodeFrame(buf('snapshot.bin'));
    if (s.type !== 'snapshot') throw new Error('wrong frame type');
    expect(s.snapshot.t).toBe(expected.snapshot.t);
    expect(s.snapshot.n).toBe(expected.snapshot.n);
    expect(Array.from(s.snapshot.form.slice(0, 20))).toEqual(expected.snapshot.form);
    const a = decodeFrame(buf('aggregates.bin'));
    if (a.type !== 'aggregates') throw new Error('wrong frame type');
    expect(a.aggregates.k).toBe(8);
    expect(a.aggregates.t).toBe(expected.aggregates.t);
  });

  it('dequantizes monotonically within bounds', () => {
    expect(dequantize(0, 10)).toBe(0);
    expect(dequantize(255, 10)).toBeCloseTo(10, 5);
    expect(dequantize(100, 10)).toBeLessThan(dequantize(101, 10));
  });
});

describe('Mirror', () => {
  it('applies snapshot + deltas and counts every event', () => {
    const snap = decodeFrame(buf('snapshot.bin'));
    const f = decodeFrame(buf('frame.bin'));
    if (snap.type !== 'snapshot' || f.type !== 'deltas') throw new Error('fixtures');
    const m = new Mirror(snap.snapshot.n);
    m.applySnapshot(snap.snapshot);
    m.applySteps(f.steps, 1000, f.bytes);
    const ign = expected.steps.reduce((a: number, s: { ignitions: number[] }) => a + s.ignitions.length, 0);
    const cuts = expected.steps.reduce((a: number, s: { cuts: number[] }) => a + s.cuts.length, 0);
    expect(m.totals.ignitions).toBe(ign);
    expect(m.totals.cuts).toBe(cuts);
    expect(m.t).toBe(expected.steps[expected.steps.length - 1].t);
    const last = expected.steps[expected.steps.length - 1];
    expect(last.diffDense).not.toBeNull();
    expect(Array.from(m.diffQ)).toEqual(last.diffDense);
  });

  it('keeps sparse edges consistent across cut / new / reconfiguration', () => {
    const m = new Mirror(4);
    m.positions.network.set([0, 0, 1, 0, 2, 0, 3, 0]);
    m.applyTile('network', {
      nodes: new Uint32Array([0, 1, 2, 3]), x: new Float32Array(4), y: new Float32Array(4),
      edges: new Uint32Array([7, 8]), src: new Uint32Array([0, 1]), dst: new Uint32Array([1, 2]),
      weight: new Float32Array([1, 1]), gate: new Float32Array([1, 1]), alive: new Uint8Array([1, 1]),
      transform: new Uint8Array([0, 0]), truncated: false,
    });
    m.applySteps([{ t: 1, cuts: new Uint32Array([7]),
      reconfigurations: { edge: new Uint32Array([8]), from: new Uint32Array([2]), to: new Uint32Array([3]) },
      newConnections: { edge: new Uint32Array([9]), src: new Uint32Array([2]), dst: new Uint32Array([0]),
        weight: new Float32Array([0.4]) } }], 0, 10);
    expect(m.edgeSrc.has(7)).toBe(false);
    expect(m.edgeDst.get(8)).toBe(3);
    expect(m.edgeSrc.get(9)).toBe(2);
    expect(m.transients.map((x) => x.kind).sort()).toEqual([2, 3, 4, 5]);
  });
});
